if arg[1] == nil or arg[1] == "-h" or arg[1] == "--help" then
    print("OpenTTY Figlet v" .. version)
    print("")
    print("Usage: figlet <text...>")
    print("")
    print("Example: figlet open tty")
    os.exit(0)
end

local input = ""
for i = 1, #arg do
    if input ~= "" then input = input .. " " end
    input = input .. arg[i]
end

input = string.upper(input)

for r = 1, 5 do
    local line = ""
    local last = #input
    for i = 1, last do
        local glyph = FONT[string.sub(input, i, i)]
        if glyph == nil then glyph = FONT["?"] end
        line = line .. glyph[r]
        if i < last then line = line .. " " end
    end
    print(line)
end